#pragma once

#include <Arduino.h>

// Простая пищалка на ШИМ.
//
// Пока нет усилителя, колонка всё равно должна подавать признаки жизни: писк
// на включении, короткий сигнал при привязке, низкий тон на ошибку. Это не речь
// и не музыка — только тональные сигналы.
//
// Работает и с пассивной пищалкой (частота задаётся ШИМ), и с активной
// (тогда частота не важна, слышен только факт включения).
namespace beeper {

// Последовательность тонов: частота в герцах и длительность в миллисекундах.
// Частота 0 — пауза.
struct Note {
  uint16_t frequency;
  uint16_t durationMs;
};

void begin();

// Поставить мелодию в очередь. Новая мелодия заменяет текущую: важнее
// сообщить актуальное состояние, чем доиграть устаревшее.
void play(const Note* notes, size_t count);

// Вызывать из главного цикла: переключает ноты без блокировки.
void tick();

void boot();
void paired();
void error();
void listening();
void connected();
void unpaired();

bool isAvailable();

}  // namespace beeper
