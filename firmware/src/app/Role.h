#pragma once

#include <stdint.h>

// DeviceRole — вариант изделия, задаётся на этапе сборки, а не приходит с
// сервера. Это не «роль» внутри одного изделия: вариантов два, и это два
// разных продукта.
//
//   Home     — умная колонка для дома: стоит на полке, слушает голос,
//              управляет светом, разговаривает с ИИ-агентом.
//   Intercom — гоночная гарнитура DED CORE INTERCOM. Её надевает пилот,
//              чтобы не снимать руки с руля во время активной гонки: голосом
//              управляет блоком зажигания, переключает карты и говорит с
//              агентом, не отвлекаясь от трассы. Здесь голос — не удобство,
//              а рабочий орган управления машиной на ходу.
//
// Общая у них только база прошивки: аудиотракт, связь и привязка устройства.
// Именно поэтому это отдельный вариант сборки, а не отдельная кодовая база —
// но изделия, их назначение и наборы команд разные.
//
// Выбор варианта — на этапе компиляции, а не по сети, по двум причинам:
// автономные команды обязаны работать без сети, а набор команд не должен
// утекать в чужое изделие — иначе один образ можно было бы превратить в
// другое устройство вместе с таблицей фраз.
enum class DeviceRole : uint8_t { Home, Intercom };

#if defined(SPEAKER_ROLE_INTERCOM)
constexpr DeviceRole kRole = DeviceRole::Intercom;
#else
constexpr DeviceRole kRole = DeviceRole::Home;
#endif
