#pragma once

#include <atomic>
#include <cstddef>
#include <cstdint>

// Компенсатор эха по референсу воспроизведения.
//
// Колонка слышит сама себя: музыка идёт в усилитель и через корпус попадает в
// микрофон. Отдельный АЦП на выходе усилителя для этого не нужен — референс
// уже есть в цифре, это ровно те отсчёты, что ушли в I2S (см.
// docs/04-hardware-bom.md). Здесь они вычитаются из микрофона адаптивным
// фильтром (NLMS), поэтому порог детектора речи можно держать по остатку
// эха, а не выше самой музыки.
//
// Частоты разные: эфир приходит 44.1 или 48 кГц, микрофон — 16 кГц. Референс
// приводится к 16 кГц фильтром против наложения и линейной интерполяцией по
// равномерной сетке: неравномерный шаг даёт «дрожащий» референс, который
// фильтр с постоянными весами вычесть не может.
//
// Референс подаётся кусками по 6 мс, сразу перед записью в I2S: блок MP3 в
// 26 мс длиннее очереди DMA, и если отдать референс целиком, его отсчёты
// зазвучат вразброс, а вычесть такой «размазанный» сигнал нечем. Отсюда же
// требование к вызывающему: пусть пишет в I2S тем же куском, что и подаёт.
//
// Задержка тракта (микрофон плюс воздух) ищется взаимной корреляцией и
// запоминается. Оценка «липкая»: новая задержка принимается, только если
// корреляция на ней заметно выше, чем на текущей. Окно фильтра начинается
// на 8 мс раньше найденной задержки, остальные 24 мс уходят на дрожание
// очереди DMA.
//
// Память: кольцо истории и окно текущего кадра, оба в int16 — референс и так
// 16-битный, а во float он занимал бы вдвое больше. Окно — две линейные копии
// из кольца: обращаться к кольцу в цикле фильтра значило бы считать остаток
// от деления на каждом отсчёте. На плате каждый килобайт статики важен:
// свободная куча нужна TLS и декодеру эфира, и без экономии эфир
// останавливался с «не удалось запустить декодер».
//
// Потоки: pushPlayback() зовёт задача декодера, process() — задача микрофона.
// Писатель один, читатель один; обмен через атомарный счётчик. Окно, которое
// читает микрофон, отстаёт от головы записи не меньше чем на длину фильтра.
class EchoCanceller {
 public:
  static constexpr uint32_t kRate = 16000;
  /// Длина фильтра должна покрывать не только сам акустический путь (пара
  /// миллисекунд), но и дрожание задержки тракта: очередь DMA то полнее, то
  /// пустее, и эхо приходит то на 20, то на 35 мс позже. Фильтр, который
  /// начинается от минимальной задержки, выучивает сразу оба пути — так
  /// линейный фильтр и компенсирует переключение между ними.
  static constexpr size_t kTaps = 384;        // 24 мс на путь и дрожание
  /// Заранее неизвестная задержка тракта. Сюда входят очереди DMA усилителя
  /// (23 мс) и микрофона (32 мс), плюс воздух. Это не 5–10 мс, как кажется:
  /// пока микрофон отдаёт кадр, он уже лежит в буферах драйвера, и именно
  /// отсюда брались «прыжки» 3–39 мс на живой плате — настоящая задержка
  /// просто не помещалась в прежние 40 мс.
  static constexpr uint32_t kMaxDelay = 1200;  // 75 мс
  /// Окно фильтра начинается раньше найденной задержки на 8 мс. Очередь DMA то
  /// полнее, то пустее, и эхо приходит то раньше, то позже найденного пика;
  /// остальные 24 мс запаса (длина фильтра) уходят на позднюю сторону. Без
  /// этого запаса назад прямой звук выпадал из окна и не вычитался.
  static constexpr uint32_t kDelayMargin = 128;
  static constexpr size_t kMaxFrame = 512;

  void begin();
  void reset();

  /// Референс: пост-гейн отсчёты, которые уходят в I2S. Стерео, своя частота.
  void pushPlayback(const int16_t* interleaved, size_t frames, uint32_t rate);

  /// Вычесть эхо из кадра микрофона (16 кГц, моно) на месте.
  void process(int16_t* samples, size_t count);

  bool ready() const { return _ready; }

  /// Оценка задержки тракта: по ней видно, что корреляция вообще нашлась.
  uint32_t delaySamples() const { return _delay; }
  float delayMs() const {
    return static_cast<float>(_delay) * 1000.0f / static_cast<float>(kRate);
  }

  /// Сколько дБ эха гасится. Меньше 6 дБ — фильтр ещё не сошёлся.
  float erleDb() const { return _erleDb; }
  bool converged() const { return _erleDb >= 6.0f; }

  /// Уровень микрофона до и после вычитания эха (RMS в отсчётах АЦП): по этим
  /// двум числам на живой плате видно, есть ли эхо вообще и что с ним стало.
  uint32_t inputRms() const { return _inputRms; }
  uint32_t outputRms() const { return _outputRms; }

  /// Лучший пик корреляции за последнее измерение — независимо от того,
  /// принят он или нет. По нему видно, есть ли вообще в референсе эхо.
  float probeScore() const { return _probeScore; }
  uint32_t probeLagMs() const {
    return static_cast<uint32_t>(static_cast<float>(_probeLag) * 1000.0f
                                 / static_cast<float>(kRate));
  }

 private:
  /// История референса: кадр, максимальная задержка и длина фильтра
  /// (512 + 1200 + 384 = 2096) плюс запас на запись во время обработки.
  static constexpr size_t kHistory = 2304;

  /// Шаг NLMS: на первых секундах большой (быстрое схождение), дальше малый
  /// (малый остаток).
  static constexpr float kMuWarmup = 0.25f;
  static constexpr float kMuSteady = 0.05f;
  static constexpr uint32_t kDelayEveryFrames = 50;  // раз в секунду

  /// Скачок задержки принимается, только если корреляция на новом месте
  /// заметно выше, чем на текущем.
  static constexpr uint32_t kDelayJumpSamples = 8;

  struct Biquad {
    float b0 = 1.0f;
    float b1 = 0.0f;
    float b2 = 0.0f;
    float a1 = 0.0f;
    float a2 = 0.0f;
    float z1 = 0.0f;
    float z2 = 0.0f;

    inline float process(float x) {
      const float y = b0 * x + z1;
      z1 = b1 * x - a1 * y + z2;
      z2 = b2 * x - a2 * y;
      return y;
    }
  };

  void designPair(Biquad& first, Biquad& second, float rate, float cutoff, bool highPass);
  void designAntiAlias(float rate);
  void designHighPass();
  void pushSample(float value);
  void fillStage(size_t span);
  void estimateDelay(const int16_t* mic, size_t count);
  /// Перенос выученных весов в окно, сдвинутое на delta отсчётов.
  void shiftTaps(int32_t delta);
  float delayScore(size_t count, uint32_t lag, float micPower, const int16_t* mic) const;
  float referencePower(size_t count, uint32_t lag) const;

  bool _ready = false;

  uint32_t _inRate = 0;
  /// Сколько входных отсчётов до следующего выходного. Шаг строго равномерный.
  float _step = 1.0f;
  float _phase = 0.0f;
  float _prevSample = 0.0f;
  Biquad _aa1;
  Biquad _aa2;

  /// Референс приводится к той же полосе, что и микрофон: у микрофонного
  /// тракта стоит отсечка 90 Гц, и без неё фильтр тратил бы весь запас на
  /// низ, которого в микрофоне всё равно нет.
  Biquad _hp1;
  Biquad _hp2;

  int16_t _history[kHistory] = {};
  std::atomic<uint32_t> _count{0};

  /// Окно референса для текущего кадра: кадр, максимальная задержка и длина
  /// фильтра. Заполняется из кольца двумя линейными копиями.
  int16_t _stage[kMaxFrame + kMaxDelay + kTaps] = {};

  float _taps[kTaps] = {};
  uint32_t _delay = 0;
  /// Кандидат на новую задержку и сколько измерений подряд он подтверждался.
  uint32_t _delayCandidate = 0;
  uint32_t _delayHits = 0;
  uint32_t _framesSinceDelay = 0;
  uint32_t _framesSinceReset = 0;
  bool _adaptNext = true;
  float _erleDb = 0.0f;
  uint32_t _inputRms = 0;
  uint32_t _outputRms = 0;
  float _probeScore = 0.0f;
  uint32_t _probeLag = 0;
};
