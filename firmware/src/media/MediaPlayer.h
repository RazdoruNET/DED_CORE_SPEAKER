#pragma once

#include <Arduino.h>

// Эфир и музыка прямо на колонке: устройство само тянет поток по HTTPS и
// декодирует его в I2S.
//
// Почему не через браузер: путь «браузер → сервер → SAY» отдаёт PCM16 16 кГц
// моно — это формат речи. Музыка в нём звучит как телефон, а трафик идёт
// непрерывно через сервер. Здесь колонка берёт поток сама: 44.1 кГц стерео,
// качество ограничено только станцией.
//
// Декодер — minimp3 (public domain, CC0): единственный доступный без GPL, а
// GPL-декодер заразил бы лицензию прошивки.
namespace media {

/// Выделить память под декодер заранее, до первого защищённого соединения.
/// После TLS в куче не остаётся цельного куска на буферы, и эфир не стартовал
/// вовсе — колонка говорила «включила радио» и молчала.
void prepare();

/// Начать эфир. Возвращает false, если поток уже играет или кончилась память
/// под задачу. Ошибки сети не пробрасываются: переподключение внутри.
bool play(const String& url, const String& title);

/// Эфир, который присылает сервер кадрами MEDIA: он уже перекодировал трек в
/// MP3, устройству остаётся декодировать. Так играет «моя музыка» любого
/// формата — M4A и AAC плата сама не разберёт.
bool beginRelay(const String& title);

/// Кусок MP3 от сервера. Не блокирует: если буфер полон, кусок теряется, и это
/// видно в строке остановки эфира.
void feed(const uint8_t* data, size_t length);

/// Остановить эфир и освободить I2S для речи.
void stop();

/// Играет ли сейчас (или буферизует) поток.
bool active();

/// Что играет: для ленты состояния и лога.
String title();

/// Речь агента важнее эфира: перед `SPEECH_BEGIN` поток останавливается, после
/// `SPEECH_END` возвращается сам. Для живого эфира это переподключение (пара
/// секунд), для трека — воспроизведение с начала.
void pauseForSpeech();
void resumeAfterSpeech();

/// Занимает ли эфир I2S прямо сейчас: пока да, речь не должна переключать порт.
bool holdsOutput();

/// Сколько байт потока принято и сколько ждёт декодера: по этим двум числам
/// видно, доехал ли эфир до платы и не пуст ли буфер.
uint32_t receivedBytesTotal();
size_t bufferedBytes();

}  // namespace media
