// Доверенный CA платформы. Пустое значение — безопасный отказ: колонка не
// поднимает TLS вообще, а не переходит в insecure-режим.
#define SPEAKER_ROOT_CA_PEM \
"-----BEGIN CERTIFICATE-----\n" \
"REPLACE_WITH_THE_PLATFORM_CA_CERTIFICATE\n" \
"-----END CERTIFICATE-----\n"

// Открытый ключ подписи привязки: несжатая точка P-256 (0x04 || X || Y),
// ровно 130 hex-символов. Именно hex, а не PEM: в предсборке mbedTLS от
// Arduino-ядра разбор PEM может быть выключен, и тогда проверка подписи молча
// отказывала бы всегда. Пока значение не заменено на настоящий ключ, прошивка
// не принимает ни один кадр привязки — это тоже безопасный отказ.
#define SPEAKER_PAIRING_PUBLIC_KEY_HEX \
"REPLACE_WITH_130_HEX_CHARACTERS_OF_THE_PAIRING_PUBLIC_KEY"

